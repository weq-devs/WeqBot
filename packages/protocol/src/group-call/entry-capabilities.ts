const capabilities = Uint8Array.from(CAPABILITIES_HEX.match(/../g)!, (pair) =>
  Number.parseInt(pair, 16),
);

export function buildGroupCallEntryBody(
  selfUin: number,
  selfUid: string,
  media: 1 | 2,
): Uint8Array {
  const uid = new TextEncoder().encode(selfUid);
  const identity = concat([
    pbVarint(1, selfUin),
    pbBytes(2, uid),
    pbVarint(3, 2),
    pbVarint(6, selfUin),
  ]);
  const tracks = [7, 1, 2].map((track) => concat([pbVarint(1, track), pbVarint(2, 1)]));
  return pbBytes(
    1,
    concat([
      pbBytes(1, capabilities),
      pbVarint(3, 0),
      pbVarint(5, 0),
      pbVarint(6, 0xffffffff),
      pbBytes(10, pbBytes(1, identity)),
      pbVarint(13, media),
      ...tracks.map((track) => pbBytes(14, track)),
      ...tracks.map((track) => pbBytes(15, track)),
    ]),
  );
}

function concat(fields: Uint8Array[]): Uint8Array {
  const result = new Uint8Array(fields.reduce((size, field) => size + field.length, 0));
  let offset = 0;
  for (const field of fields) {
    result.set(field, offset);
    offset += field.length;
  }
  return result;
}
