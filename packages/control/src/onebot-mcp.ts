export type OneBotMcpAccess = 'read' | 'write';

export function oneBotMcpAccess(name: string): OneBotMcpAccess | undefined {
  if (readActions.has(name)) return 'read';
  if (writeActions.has(name)) return 'write';
}

/** 路径和富消息段继续由 OneBot 原有接入处理。MCP 的这几项只接受文本。 */
export function oneBotMcpTextFields(name: string): readonly string[] {
  switch (name) {
    case 'send_msg':
    case 'send_group_msg':
    case 'send_private_msg':
      return ['message'];
    case 'send_qzone_msg':
      return ['content'];
    case '_send_group_notice':
      return ['content'];
    default:
      return [];
  }
}

export function oneBotMcpBlockedFields(name: string): readonly string[] {
  switch (name) {
    case 'send_qzone_msg':
      return ['images'];
    case '_send_group_notice':
      return ['image'];
    default:
      return [];
  }
}
